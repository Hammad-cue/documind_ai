"""
Collect every evaluation result into docs/EVALUATION.md (tables you can paste into the report).

    python -m evaluation.report
"""
import json
from pathlib import Path

from evaluation.common import RESULTS, ROOT, save

OUT = ROOT / 'docs' / 'EVALUATION.md'


def load(name):
    p = RESULTS / f'{name}.json'
    return json.loads(p.read_text(encoding='utf-8')) if p.exists() else None


def latest(pattern):
    files = sorted((ROOT / 'ml' / 'runs').glob(pattern), key=lambda p: p.stat().st_mtime)
    return json.loads(files[-1].read_text(encoding='utf-8')) if files else None


def pct(x):
    """0.8845 -> '88.5%' (round half up, as in the written report)."""
    from decimal import ROUND_HALF_UP, Decimal
    return '—' if x is None else f"{(Decimal(str(x)) * 100).quantize(Decimal('0.1'), ROUND_HALF_UP)}%"


def collect_clauses():
    """Copy the clause-classification numbers out of ml/runs (git-ignored) into evaluation/results."""
    rows = []
    by_size = {}
    for f in sorted((ROOT / 'ml' / 'runs').glob('baseline-tfidf-*.json'), key=lambda p: p.stat().st_mtime):
        t = json.loads(f.read_text(encoding='utf-8'))
        by_size[t.get('train_examples', 60000)] = t   # latest run per training-set size
    for size, t in sorted(by_size.items()):
        rows.append({'model': 'TF-IDF + logistic regression (baseline)', 'train_examples': size,
                     **{k: t[k] for k in ('test_examples', 'accuracy', 'macro_f1')}})
    llm = latest('baseline-llm-zero-shot-*.json')
    if llm:
        rows.append({'model': f"Zero-shot LLM ({llm['model'].replace('zero-shot ', '')})", 'test_examples': llm['test_examples'],
                     'accuracy': llm['accuracy'], 'macro_f1': llm['macro_f1'], 'train_examples': 0})
    for run in sorted((ROOT / 'ml' / 'runs').glob('*/metrics.json'), key=lambda p: p.stat().st_mtime)[-1:]:
        m = json.loads(run.read_text(encoding='utf-8'))
        rows.append({'model': f"Fine-tuned {m['model'].split('/')[-1]} (ours)", 'test_examples': m['test_examples'],
                     'accuracy': m.get('accuracy'), 'macro_f1': m.get('macro_f1'), 'train_examples': m['train_examples'],
                     'epochs': m.get('epochs'), 'train_minutes': m.get('train_minutes')})
    ens = latest('ensemble-*.json')
    if ens:
        t = ens['test']['ensemble']
        rows.append({'model': f"Fine-tuned MiniLM + TF-IDF, averaged (ours, weight {ens['transformer_weight']})",
                     'test_examples': ens['test_examples'], 'accuracy': t['accuracy'], 'macro_f1': t['macro_f1'],
                     'train_examples': ens['train_examples']})
    if rows:
        save('clauses_ledgar', {'rows': rows})
    return rows


def main():
    lines = ['# DocuMind AI — Evaluation results', '',
             'Generated by `python -m evaluation.report` from the JSON files in `evaluation/results/`.', '']

    # 1. clause classification
    clauses = collect_clauses()
    lines += ['## 1. Clause classification (LEDGAR, 100 clause types)', '',
              '| Model | Training clauses | Test clauses | Accuracy | Macro-F1 |', '|---|---:|---:|---:|---:|']
    for r in clauses:
        lines.append(f"| {r['model']} | {r['train_examples']:,} | {r['test_examples']:,} | {pct(r['accuracy'])} | {pct(r['macro_f1'])} |")
    if not clauses:
        lines.append('| _not run yet_ | | | | |')
    lines += ['', 'Macro-F1 averages over all 100 clause types, so rare types count as much as common ones.', '']
    ours = next((r for r in clauses if 'ours' in r['model']), None)
    if ours and ours['train_examples'] < 60000:
        lines += [f"> The fine-tuned model was trained on a laptop CPU: {ours['train_examples']:,} clauses, {ours.get('epochs')} epochs, "
                  f"{ours.get('train_minutes')} minutes. Its validation score was still rising every epoch, so it is under-trained "
                  'rather than a weaker approach. Compare it with TF-IDF on the same training size; for the final result, run '
                  '`ml/colab_train_clause_classifier.ipynb` on a free GPU with all 60,000 clauses.', '']

    # 2. retrieval
    r = load('retrieval_cuad')
    lines += ['## 2. Retrieval (CUAD, searching inside one contract for a clause the lawyers marked)', '']
    if r:
        lines += [f"{r['contracts']} contracts, {r['results']['structure']['modes']['hybrid']['queries']} questions per configuration. "
                  'A hit means the returned passage contains the lawyers\' answer span.', '',
                  '| Chunking | Retrieval | Hit@1 | Hit@3 | Hit@5 | MRR@10 |', '|---|---|---:|---:|---:|---:|']
        names = {'structure': 'Section-aware (ours)', 'fixed': 'Fixed 1000 chars (v1)'}
        modes = {'dense': 'Semantic only', 'sparse': 'Keyword only', 'hybrid': 'Hybrid RRF (ours)'}
        for s in ('fixed', 'structure'):
            for m in ('dense', 'sparse', 'hybrid'):
                v = r['results'][s]['modes'][m]
                lines.append(f"| {names[s]} | {modes[m]} | {pct(v['hit@1'])} | {pct(v['hit@3'])} | {pct(v['hit@5'])} | {v['mrr@10']:.3f} |")
        old = r['results']['fixed']['modes']['dense']
        new = r['results']['structure']['modes']['hybrid']
        lines += ['', f"**v1 setup (fixed chunks, semantic only) → this system (section-aware, hybrid):** "
                      f"Hit@1 {pct(old['hit@1'])} → {pct(new['hit@1'])}, Hit@5 {pct(old['hit@5'])} → {pct(new['hit@5'])}.", '']
    else:
        lines += ['_not run yet_', '']

    # 3. extraction
    e = load('extraction_cuad')
    lines += ['## 3. Record field extraction (CUAD)', '']
    if e:
        s = e['summary']
        lines += [f"{s['contracts_evaluated']} contracts ({s['contracts_skipped']} skipped), model `{s['model']}`, "
                  f"{s['seconds_per_contract']} s per contract. A prediction is correct when its quoted evidence overlaps the "
                  'lawyers\' span or its value matches (same date / parties / jurisdiction).', '',
                  '| Field | Precision | Recall | F1 |', '|---|---:|---:|---:|']
        for k, v in s['per_field'].items():
            lines.append(f"| {k.replace('_', ' ')} | {pct(v['precision'])} | {pct(v['recall'])} | {pct(v['f1'])} |")
        m = s['micro']
        g = s['grounding']
        n_pred = sum(g['grounded'].values()) + sum(g['ungrounded'].values())
        n_grounded = sum(g['grounded'].values())
        lines += [f"| **All fields (micro)** | **{pct(m['precision'])}** | **{pct(m['recall'])}** | **{pct(m['f1'])}** |", '',
                  '**Evidence and review**', '',
                  f"- Quotes found word-for-word on the cited page: **{n_grounded}/{n_pred}** ({pct(n_grounded / n_pred if n_pred else None)}) "
                  '— the model almost never invents evidence, so every value can be checked against its page.',
                  f"- Wrong predictions already sent to the human review queue: **{s['review_queue']['wrong_predictions_flagged']}** "
                  f"(right ones sent: {s['review_queue']['right_predictions_flagged']}). Most errors carry a real quote that answers "
                  'a slightly different question, so confidence and grounding alone do not catch them — a limitation and a direction '
                  'for future work (e.g. a second model checking each value against its field definition).', '',
                  '**Reading these numbers**', '',
                  "- CUAD's labels differ from ours for two fields. *Notice Period To Terminate Renewal* covers only notice to stop a "
                  "renewal, while our *notice period* is any termination notice — so many of our correct values count as false "
                  "positives. *Expiration Date* is often a duration (\"continues for five years\"), while we extract an explicit date "
                  'only when one is written, which lowers recall.',
                  '- Parties, signing date, effective date and governing law use the same definitions as CUAD and are the fairest measure.', '']
    else:
        lines += ['_not run yet_', '']

    # 3a. second check and calculated expiry dates
    v = load('verifier_cuad')
    if v:
        sv = v['summary']
        lines += ['## 3a. Second check on extracted values', '',
                  f"The check (model `{sv['model']}`) re-read the {sv['checked_values']} saved predictions: it flagged "
                  f"**{sv['wrong_flagged']}/{sv['wrong_values']}** wrong values ({pct(sv['wrong_flagged_rate'])}) and "
                  f"{sv['right_flagged']}/{sv['right_values']} right ones ({pct(sv['right_flagged_rate'])}). Before it, the review rule "
                  "caught 2 of 34 wrong values.", '']
    x = load('expiry_cuad')
    if x:
        sx = x['summary']
        a, b = sx['without_calculation'], sx['with_calculation']
        lines += ['## 3b. Expiry dates calculated from start date + term', '',
                  f"{sx['re_extracted']} contracts without a written expiry date were extracted again (model `{sx['model']}`); "
                  f"{sx['calculated_values']} expiry dates were calculated ({sx['calculated_right']} right, {sx['calculated_wrong']} wrong).", '',
                  '| Expiry date | Precision | Recall | F1 |', '|---|---:|---:|---:|',
                  f"| Without calculation | {pct(a['precision'])} | {pct(a['recall'])} | {pct(a['f1'])} |",
                  f"| With calculation | {pct(b['precision'])} | {pct(b['recall'])} | {pct(b['f1'])} |", '']

    # 3c. answers
    a = load('answers_cuad')
    lines += ['## 3c. Answer quality (CUAD, questions asked through the full answer engine)', '']
    if a:
        s = a['summary']
        lines += [f"{s['contracts']} contracts, {s['answerable_questions']} questions whose answer is in the contract and "
                  f"{s['unanswerable_questions']} whose answer is not. Model `{s['model']}`.", '',
                  '| Measure | Result |', '|---|---:|',
                  f"| Answer judged correct against the lawyers' span | {pct(s['answer_correct_rate'])} |",
                  f"| At least one cited passage contains the lawyers' span | {pct(s['citation_hit_rate'])} |",
                  f"| Answers that cite their sources | {pct(s['answers_with_citations'])} |",
                  f"| Says \"not in the document\" when the clause is absent | {pct(s['abstention_rate_when_absent'])} |",
                  f"| Wrongly says \"not in the document\" when it is | {pct(s['wrongly_abstained_when_present'])} |", '',
                  'Correctness is graded by a second LLM call that sees the lawyers\' annotation (LLM-as-judge); spot-check '
                  'a sample by hand before relying on it.', '']
    else:
        lines += ['_not run yet_', '']

    # 4. routing
    rt = load('router')
    lines += ['## 4. Query routing (100 labelled questions)', '']
    if rt:
        lines += ['| Router | Accuracy | Lookup F1 | Knowledge F1 | Search F1 | Correct field (lookups) | Time |', '|---|---:|---:|---:|---:|---:|---:|']
        for name, label in (('heuristic', 'Keyword rules (fallback)'), ('llm', f"LLM router ({rt['model']})")):
            v = rt[name]
            pi = v['per_intent']
            lines.append(f"| {label} | {pct(v['accuracy'])} | {pct(pi['LOOKUP']['f1'])} | {pct(pi['KNOWLEDGE']['f1'])} | "
                         f"{pct(pi['SEARCH']['f1'])} | {pct(v['field_accuracy_on_lookups'])} | {v['avg_ms']} ms |")
        fb = rt['llm'].get('llm_fallbacks')
        if fb:
            lines += ['', f'> {fb} of the LLM router\'s answers came from the keyword fallback because the API rate-limited the call.']
        lines += ['', 'LLM router confusion (rows = correct route, columns = predicted):', '',
                  '| | LOOKUP | KNOWLEDGE | SEARCH |', '|---|---:|---:|---:|']
        for g, row in rt['llm']['confusion'].items():
            lines.append(f"| {g} | {row.get('LOOKUP', 0)} | {row.get('KNOWLEDGE', 0)} | {row.get('SEARCH', 0)} |")
        lines.append('')
    else:
        lines += ['_not run yet_', '']

    # 5. handwriting
    h = load('handwriting_real') or load('handwriting_synthetic')
    lines += ['## 5. Handwriting recognition', '']
    if h:
        s = h['summary']
        lines += [f"Dataset: {s['dataset']} ({s['images']} pages). Character / word error rate — lower is better.", '',
                  '| Reader | CER | WER | Time per page |', '|---|---:|---:|---:|',
                  f"| Tesseract OCR | {pct(s['tesseract_cer'])} | {pct(s['tesseract_wer'])} | {s['tesseract_ms']:.0f} ms |",
                  f"| Vision model ({s['vision_model']}) | {pct(s['vision_cer'])} | {pct(s['vision_wer'])} | {s['vision_ms']:.0f} ms |",
                  f"| Pipeline (vision only when Tesseract is unsure; {s['sent_to_vision']}/{s['images']} pages sent) | {pct(s['pipeline_cer'])} | | |", '']
        if 'synthetic' in s['dataset']:
            lines += ['> Synthetic set (handwriting-style fonts). Real handwriting is harder: rerun with real scans via '
                      '`python -m evaluation.eval_handwriting --folder <scans>` before quoting these numbers.', '']
    else:
        lines += ['_not run yet_', '']

    lines += ['## 6. Access control', '', 'Automated tests (`python manage.py test`) check the full role × access-level matrix, that '
              'search never returns chunks from documents a user may not open (including when forbidden document ids are passed '
              'explicitly), that files are only served through the permission-checked endpoint, and that the audit log cannot be '
              'edited or deleted.', '']
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
